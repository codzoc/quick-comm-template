export const getThemeTemplate = (templateKey) => {
  return themeTemplates[templateKey] || themeTemplates[defaultTemplate];
};

export const getThemeTemplateOptions = () => {
  return Object.keys(themeTemplates).map((key) => ({
    value: key,
    label: themeTemplates[key].name,
    description: themeTemplates[key].description,
  }));
};
